#!/usr/bin/env node
/**
 * Build the portable, extract-and-run Windows bundle.
 *
 *   node scripts/build-portable.mjs --out <dir> [--with-admin] [--node <dir>]
 *
 * Produces:
 *
 *   <dir>/Tech-Radar-Portable/
 *   ├── runtime/                 bundled Node.js (copied from --node)
 *   ├── app/                     project + node_modules + current data
 *   ├── Start Tech Radar.bat     launcher
 *   └── README.txt               end-user quick start
 *
 * By default the admin console is EXCLUDED (`src/admin/`, `admin.html`) and
 * the staged app gets a `.env` setting `VITE_RADAR_ONLY=true`, which makes
 * src/App.tsx ignore the `pnm-radar-published` localStorage override. That
 * override exists only so the admin console can pin a curated snapshot; with
 * no admin console shipped there would be no way to clear it, so a snapshot
 * left over from a full build (same origin — localhost:5173 — hence the same
 * localStorage) would silently freeze the radar on stale data.
 *
 * Pass --with-admin to build the full two-page bundle instead.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");

/* ─────────────────────────── args ─────────────────────────── */

function parseArgs(argv) {
  const args = { withAdmin: false, out: null, node: null };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === "--with-admin") args.withAdmin = true;
    else if (arg === "--out") args.out = argv[++i];
    else if (arg === "--node") args.node = argv[++i];
    else throw new Error(`Unknown argument: ${arg}`);
  }
  if (!args.out) throw new Error("--out <dir> is required");
  return args;
}

/** Default to the directory holding the node.exe running this script. */
function defaultNodeDir() {
  return path.dirname(process.execPath);
}

/* ───────────────────────── staging ────────────────────────── */

/**
 * Paths excluded from the staged app, relative to ROOT and compared
 * case-insensitively (Windows). Anything at or below these is skipped.
 */
function exclusions(withAdmin) {
  const shared = [
    ".git",
    "dist", // project build output — the bundle runs the dev server
    "data/logs", // historical scrape logs; the app writes fresh ones
    ".claude", // editor/agent workspace settings, not app code
    ".cursor",
    "serve.log",
    "node_modules/.vite", // dep cache holds absolute paths from THIS machine
  ];
  return withAdmin ? shared : [...shared, "src/admin", "admin.html"];
}

function makeFilter(excluded) {
  const normalized = excluded.map((p) => p.replace(/\\/g, "/").toLowerCase());
  return (src) => {
    const rel = path.relative(ROOT, src).replace(/\\/g, "/").toLowerCase();
    if (!rel) return true;
    return !normalized.some((ex) => rel === ex || rel.startsWith(`${ex}/`));
  };
}

/* ───────────────────────── templates ──────────────────────── */

const LAUNCHER = `@echo off
setlocal EnableExtensions
title Tech Radar

REM ===========================================================================
REM  Tech Radar - Portable Launcher (Windows x64)
REM  Generated by scripts/build-portable.mjs - do not edit by hand.
REM
REM  1. Uses the bundled Node.js in runtime\\ (no system install required)
REM  2. Hands off to scripts\\serve-portable.mjs, which picks the first FREE
REM     port from 5173 upwards and opens the radar in your default browser
REM  Close this console window to stop the server.
REM ===========================================================================

set "ROOT=%~dp0"
set "ROOT=%ROOT:~0,-1%"

if not exist "%ROOT%\\runtime\\node.exe" goto :incomplete
if not exist "%ROOT%\\app\\scripts\\serve-portable.mjs" goto :incomplete
if not exist "%ROOT%\\app\\node_modules\\vite\\dist\\node\\cli.js" goto :incomplete

REM Put the bundled runtime FIRST on PATH. The "Rescrape now" button shells
REM out to \`npm run scrape\`, so npm.cmd must resolve to our runtime too.
set "PATH=%ROOT%\\runtime;%PATH%"

echo.
echo   Tech Radar - Portable
echo   =====================
echo.
echo   Starting the server ...
echo   (first start takes ~10s while Vite prebundles dependencies)
echo   Your browser opens automatically once it is ready.
echo.

REM serve-portable.mjs picks a free port and opens the browser itself — it is
REM the only thing that knows which port it settled on. Do NOT hard-code a
REM URL here, and do NOT use scripts/serve.mjs: that one force-kills whatever
REM holds port 5173, which fights any other Tech Radar instance forever.
pushd "%ROOT%\\app"
"%ROOT%\\runtime\\node.exe" scripts\\serve-portable.mjs
set "EXITCODE=%ERRORLEVEL%"
popd

echo.
echo Server stopped (exit code %EXITCODE%).
pause
endlocal
exit /b %EXITCODE%

:incomplete
echo.
echo [ERROR] This folder is incomplete - some files are missing.
echo.
echo         Extract the .zip fully before running this launcher.
echo         Windows Explorer sometimes fails on deeply nested paths;
echo         if that happens, extract with 7-Zip instead, or move the
echo         .zip closer to the drive root (e.g. C:\\Tech-Radar\\).
echo.
pause
exit /b 1
`;

